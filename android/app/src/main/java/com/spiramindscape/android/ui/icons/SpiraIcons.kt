/**
 * Builds a Gravity UI glyph: a 16x16 box with the line drawn as an even-odd filled shape, so it
 * carries no stroke width of its own. Rendered into a 24dp box, which is every call site's size.
 */
private fun gravity(vararg paths: String): ImageVector =
    ImageVector.Builder(
        name = "gravity",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 16f,
        viewportHeight = 16f,
    ).apply {
        paths.forEach { data ->
            addPath(
                pathData = addPathNodes(data),
                pathFillType = PathFillType.EvenOdd,
                fill = SolidColor(Color.Black), // tinted by the Icon composable at draw time
            )
        }
    }.build()
