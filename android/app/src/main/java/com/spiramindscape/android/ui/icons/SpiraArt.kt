/**
 * Multi-colour illustrations. Unlike [SpiraIcons] — single-path glyphs the `Icon` composable tints
 * — these carry their own colours, so they are built per-use rather than tinted at draw time.
 */
object SpiraArt {

    /**
     * The target card's calendar: a hand-drawn spiral-bound page with a coloured header band and a
     * blank paper below it, which is where the card prints the month and day.
     *
     * The artwork is the owner's (2026-08-07). Its own coral is `#F45D48`, a hair off the brand
     * accent; it is drawn in **Guava-500** so the tile stays inside the palette, and [bandColor]
     * lets an overdue tile take the semantic error red instead.
     */
    fun calendarPage(
        bandColor: Color = Guava500,
        inkColor: Color = Salt1000,
        pageColor: Color = Color.White,
    ): ImageVector = ImageVector.Builder(
        name = "spira-calendar",
        defaultWidth = 50.dp,
        defaultHeight = 50.dp,
        viewportWidth = 50f,
        viewportHeight = 50f,
    ).apply {
        // 1. the paper
        addPath(
            pathData = addPathNodes("M44.532 11.078H5.32v33.92h39.212v-33.92Z"),
            pathFillType = PathFillType.NonZero,
            fill = SolidColor(pageColor),
        )
        // 2. the header band across the top of the page
        addPath(
            pathData = addPathNodes(
                "M44.532 18.6H19.117c-1.018 0-2.033.073-3.048.138-.6.038-3.045.356-1.884-1" +
                    "a40.347 40.347 0 0 1 5.114-5 6.13 6.13 0 0 1 3.255-1.379c.524-.085 1.09-.03 1.62-.07" +
                    ".73-.055 1.485-.009 2.217-.009h18.141v7.32Z",
            ),
            pathFillType = PathFillType.NonZero,
            fill = SolidColor(bandColor),
        )
        // 3. the drawn outline: the frame and the two binding rings
        addPath(
            pathData = addPathNodes(CALENDAR_OUTLINE),
            pathFillType = PathFillType.EvenOdd,
            fill = SolidColor(inkColor),
        )
    }.build()

    /**
     * The "no deadline yet" plus, drawn in the same hand-made hand as [calendarPage] so the two
     * read as one illustration rather than an icon dropped onto artwork. The owner's source
     * (2026-08-07) fills it with the same coral as the calendar's header band; it is drawn in
     * [fillColor] instead — repeating the band's colour a centimetre below it only muddied both.
     *
     * The source viewBox is offset (`16.05 17.5 32 32`), so the paths are translated back to the
     * origin by a group rather than being rewritten by hand.
     */
    fun plusMark(
        fillColor: Color = Kale500,
        inkColor: Color = Salt1000,
    ): ImageVector = ImageVector.Builder(
        name = "spira-plus",
        defaultWidth = 32.dp,
        defaultHeight = 32.dp,
        viewportWidth = 32f,
        viewportHeight = 32f,
    ).apply {
        addGroup(name = "viewbox", translationX = -16.05f, translationY = -17.5f)
        addPath(
            pathData = addPathNodes(PLUS_FILL),
            pathFillType = PathFillType.NonZero,
            fill = SolidColor(fillColor),
        )
        addPath(
            pathData = addPathNodes(PLUS_OUTLINE),
            pathFillType = PathFillType.EvenOdd,
            fill = SolidColor(inkColor),
        )
        clearGroup()
    }.build()

    /**
     * The seedling that heads the assistant's empty state — the owner's illustration (2026-08-07).
     *
     * **The watering can is gone** (owner, 2026-10-08: "везде где svg лейка поливает росток, нужно
     * удалить лейку и оставить только росток"). It used to be a can tipped over the plant, and at
     * the sizes this is actually drawn at the can was most of the picture while the plant was a
     * few pixels in the corner of it. The web drops the same two passes
     * (`src/components/spira/SproutArt.tsx`), so the two surfaces keep showing one picture.
     *
     * The source frame was 50x51 with the plant down in its bottom-right corner, so the viewport
     * is the plant's own bounding box — measured `31.77..49.60` across and `32.37..50.66` down,
     * squared off and padded by a quarter unit — and the paths are moved into it by a group
     * translation, which is the only offset an `ImageVector` has (there is no `viewBox` origin).
     *
     * It is art, not a glyph, so it is drawn with [androidx.compose.foundation.Image] rather than
     * `Icon`: an `Icon` would flatten all three paths to one tint and lose the leaf. Its green
     * sits a hair off the ramp and is drawn as **Kale-300**, the same snap-to-palette the calendar
     * art makes.
     */
    fun sprout(
        leafColor: Color = Kale300,
        inkColor: Color = Salt1000,
        highlightColor: Color = Color.White,
    ): ImageVector = ImageVector.Builder(
        name = "spira-sprout",
        defaultWidth = 19.dp,
        defaultHeight = 19.dp,
        viewportWidth = 18.8f,
        viewportHeight = 18.8f,
    ).apply {
        addGroup(name = "viewbox", translationX = -31.29f, translationY = -32.12f)
        // Painted back to front, exactly as the source stacks them: the highlight, the leaf, then
        // the ink pass that draws the outline over the top.
        addPath(addPathNodes(SPROUT_WHITE), fill = SolidColor(highlightColor))
        addPath(addPathNodes(SPROUT_LEAF), fill = SolidColor(leafColor))
        addPath(addPathNodes(SPROUT_INK), pathFillType = PathFillType.EvenOdd, fill = SolidColor(inkColor))
        clearGroup()
    }.build()
}

